"""Look at every CLAUDE.md / AGENTS.md pair, decide what to do, and do it.

A pair is one folder's CLAUDE.md and AGENTS.md, or your global ~/.claude/CLAUDE.md and
~/.codex/AGENTS.md. For each pair:

  only CLAUDE.md                     copy it to AGENTS.md (imports resolved, for Codex)
  only AGENTS.md                     copy it to CLAUDE.md
  same text, or CLAUDE.md is         nothing to do
    just `@AGENTS.md`, or a symlink
  both exist and differ              look at what changed since the last sync:
    - only CLAUDE.md changed           copy it over AGENTS.md
    - only AGENTS.md changed           copy it over CLAUDE.md
    - both changed / never synced      merge them with a coding agent (see merge.py)

New files inside a git repository are listed in its .git/info/exclude, so they stay local.
Every overwrite is backed up first (state.py).
"""

from __future__ import annotations

import os
import re
import subprocess
from dataclasses import dataclass, field
from pathlib import Path

from . import merge as m
from . import render as r
from .state import State, digest

SKIP_DIRS = {"node_modules", "vendor", "__pycache__", "venv", "target", "dist", "bower_components"}
EXCLUDE_COMMENT = "# claude-md-for-codex: local copy of CLAUDE.md / AGENTS.md"
LEGACY_EXCLUDE_COMMENT = "# claude-md-for-codex: generated Codex copy of CLAUDE.md (local only)"
CODEX_DEFAULT_MAX_BYTES = 32 * 1024
_CONFLICT = re.compile(r"^(<{7}|>{7})( |$)", re.M)


@dataclass
class Env:
    home: Path
    claude_dir: Path
    codex_home: Path

    @classmethod
    def from_os(cls) -> "Env":
        home = Path.home()
        claude_dir = Path(os.environ.get("CLAUDE_CONFIG_DIR") or home / ".claude").expanduser()
        codex_home = Path(os.environ.get("CODEX_HOME") or home / ".codex").expanduser()
        return cls(home, claude_dir, codex_home)


@dataclass
class Pair:
    kind: str  # global | project
    folder: Path
    claude: Path
    agents: Path
    key: str
    allowed_root: Path | None


@dataclass
class Analysis:
    pair: Pair
    case: str
    action: str  # none | create-agents | create-claude | update-agents | update-claude | merge | remove-agents | blocked
    detail: str = ""
    warnings: list[str] = field(default_factory=list)
    claude_text: str | None = None
    agents_text: str | None = None
    view: str | None = None  # what Codex should read for the current CLAUDE.md
    style: str = "copy"  # copy | imports | stub (how CLAUDE.md relates to AGENTS.md)
    stub_token: str | None = None

    @property
    def pending(self) -> bool:
        return self.action not in {"none", "blocked"}


CASES = {
    "claude-only": "only CLAUDE.md",
    "agents-only": "only AGENTS.md",
    "same": "in sync",
    "shared": "in sync (CLAUDE.md imports AGENTS.md)",
    "linked": "in sync (one is a symlink to the other)",
    "claude-changed": "CLAUDE.md changed since the last sync",
    "agents-changed": "AGENTS.md changed since the last sync",
    "both-changed": "both changed since the last sync",
    "unsynced": "they differ and were never synced",
    "stub-extra": "CLAUDE.md imports AGENTS.md but adds text Codex does not see",
    "legacy": "AGENTS.md was generated by claude-md-for-codex 0.1",
    "orphan": "AGENTS.md was generated by 0.1 from a CLAUDE.md that is gone",
    "conflict": "has git conflict markers",
    "unreadable": "cannot be read as UTF-8 text",
}
ACTIONS = {
    "none": "nothing to do",
    "create-agents": "copy CLAUDE.md -> AGENTS.md",
    "create-claude": "copy AGENTS.md -> CLAUDE.md",
    "update-agents": "copy CLAUDE.md over AGENTS.md",
    "update-claude": "copy AGENTS.md over CLAUDE.md",
    "merge": "merge with a coding agent",
    "remove-agents": "delete AGENTS.md",
    "blocked": "skipped",
}


def _read(path: Path) -> str | None:
    try:
        return path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return None


def _norm(text: str) -> str:
    return text.replace("\r\n", "\n").rstrip()


def _same_file(a: Path, b: Path) -> bool:
    try:
        return a.exists() and b.exists() and os.path.samefile(a, b)
    except OSError:
        return False


# ---------------------------------------------------------------- discovery


def find_folders(root: Path, max_depth: int, home: Path) -> list[Path]:
    """Folders under root with CLAUDE.md, .claude/ or AGENTS.md, skipping dependencies."""
    names = {"CLAUDE.md", "AGENTS.md", ".claude"}
    home_real = home.resolve()
    out: list[Path] = []
    stack = [(root, 0)]
    while stack:
        folder, depth = stack.pop()
        try:
            entries = list(os.scandir(folder))
        except OSError:
            continue
        if any(e.name in names for e in entries) and Path(folder).resolve() != home_real:
            out.append(Path(folder))
        if depth >= max_depth:
            continue
        for e in entries:
            if e.name.startswith(".") or e.name in SKIP_DIRS:
                continue
            try:
                if e.is_dir(follow_symlinks=False):
                    stack.append((Path(e.path), depth + 1))
            except OSError:
                continue
    return sorted(out)


def _project_root(folder: Path) -> Path:
    for parent in [folder, *folder.parents]:
        if (parent / ".git").exists():
            return parent
    return folder


def global_pair(env: Env) -> Pair:
    return Pair("global", env.claude_dir, env.claude_dir / "CLAUDE.md", env.codex_home / "AGENTS.md",
                "global", None)


def project_pair(folder: Path, allow_external: bool) -> Pair | None:
    claude = folder / "CLAUDE.md"
    if not claude.is_file() and (folder / ".claude" / "CLAUDE.md").is_file():
        claude = folder / ".claude" / "CLAUDE.md"
    agents = folder / "AGENTS.md"
    if not claude.is_file() and not agents.is_file():
        return None
    return Pair("project", folder, claude, agents, "project:" + str(folder.resolve()),
                None if allow_external else _project_root(folder))


# ---------------------------------------------------------------- analysis


def analyze(pair: Pair, state: State, home: Path) -> Analysis | None:
    has_c, has_a = pair.claude.is_file(), pair.agents.is_file()
    if not has_c and not has_a:
        return None
    if has_c and has_a and _same_file(pair.claude, pair.agents):
        return Analysis(pair, "linked", "none")
    c_text = _read(pair.claude) if has_c else None
    a_text = _read(pair.agents) if has_a else None
    for name, present, text in (("CLAUDE.md", has_c, c_text), ("AGENTS.md", has_a, a_text)):
        if present and text is None:
            return Analysis(pair, "unreadable", "blocked", f"{name} {CASES['unreadable']}")
        if text is not None and _CONFLICT.search(text):
            return Analysis(pair, "conflict", "blocked", f"{name} {CASES['conflict']}")

    if not has_c:
        if r.is_legacy_generated(a_text):
            return Analysis(pair, "orphan", "remove-agents", agents_text=a_text)
        return Analysis(pair, "agents-only", "create-claude", claude_text=None, agents_text=a_text)

    view, warnings = r.codex_view(pair.claude, c_text, home, skip=pair.agents, allowed_root=pair.allowed_root)
    a = Analysis(pair, "", "none", warnings=warnings, claude_text=c_text, agents_text=a_text, view=view)
    a.style = "imports" if view != c_text else "copy"
    if not has_a:
        a.case, a.action = "claude-only", "create-agents"
        return a

    token = r.imports_file(c_text, pair.claude.parent, home, pair.agents)
    if token:
        a.style, a.stub_token = "stub", token
        extra = r.residual_text(c_text, pair.claude.parent, home) or view != c_text
        if not extra:
            a.case = "shared"
            return a
        a.case, a.action = "stub-extra", "merge"
        return a
    if r.is_legacy_generated(a_text):
        a.case, a.action = "legacy", "update-agents"
        return a
    if _norm(view) == _norm(a_text):
        a.case = "same"
        return a

    base = state.baseline(pair.key)
    if base is None:
        a.case, a.action = "unsynced", "merge"
        return a
    c_changed = digest(c_text) != base["claude"] or digest(view) != base["view"]
    a_changed = digest(a_text) != base["agents"]
    if not c_changed and not a_changed:
        a.case = "same"  # as the last sync left them (e.g. AGENTS.md text that Claude reads as imports)
    elif c_changed and not a_changed:
        a.case, a.action = "claude-changed", "update-agents"
    elif a_changed and not c_changed:
        a.case = "agents-changed"
        a.action = "update-claude" if a.style == "copy" else "merge"
    else:
        a.case, a.action = "both-changed", "merge"
    return a


def max_bytes_warning(a: Analysis, max_bytes: int) -> None:
    text = a.view if a.action in {"create-agents", "update-agents"} else None
    if a.pair.kind == "project" and text is not None and len(text.encode()) > max_bytes:
        a.warnings.append(f"AGENTS.md would be {len(text.encode())} bytes, over Codex's "
                          f"project_doc_max_bytes ({max_bytes}); Codex will cut it off")


def build_plan(env: Env, roots: list[Path], state: State, *, include_global: bool = True, max_depth: int = 8,
               allow_external: bool = False, max_bytes: int = CODEX_DEFAULT_MAX_BYTES) -> list[Analysis]:
    pairs: list[Pair] = []
    if include_global:
        pairs.append(global_pair(env))
    seen: set[Path] = set()
    for root in roots:
        for folder in find_folders(root, max_depth, env.home):
            real = folder.resolve()
            if real in seen:
                continue
            seen.add(real)
            p = project_pair(folder, allow_external)
            if p is not None:
                pairs.append(p)
    plan: list[Analysis] = []
    for p in pairs:
        a = analyze(p, state, env.home)
        if a is None:
            continue
        max_bytes_warning(a, max_bytes)
        if p.kind == "global":
            override = env.codex_home / "AGENTS.override.md"
            if (_read(override) or "").strip():
                a.warnings.append(f"{override} exists, so Codex reads it instead of AGENTS.md")
        plan.append(a)
    return plan


# ---------------------------------------------------------------- git helpers


def _git(folder: Path, *args: str) -> subprocess.CompletedProcess | None:
    try:
        return subprocess.run(["git", "-C", str(folder), *args], capture_output=True, text=True, timeout=20)
    except (OSError, subprocess.SubprocessError):
        return None


def git_busy(folder: Path) -> str | None:
    """Name of a git operation in progress in folder's work tree (merge, rebase...), if any."""
    res = _git(folder, "rev-parse", "--absolute-git-dir")
    if res is None or res.returncode != 0:
        return None
    gitdir = Path(res.stdout.strip())
    for name, what in (("MERGE_HEAD", "merge"), ("rebase-merge", "rebase"), ("rebase-apply", "rebase"),
                       ("CHERRY_PICK_HEAD", "cherry-pick"), ("REVERT_HEAD", "revert")):
        if (gitdir / name).exists():
            return what
    return None


def _repo_pattern(path: Path, toplevel: str) -> str | None:
    """`/dir/AGENTS.md` relative to the work tree. git reports real paths, so compare real paths
    (on macOS /var is a symlink to /private/var; a code folder may be a symlink too)."""
    rel = os.path.relpath(os.path.realpath(path), os.path.realpath(toplevel)).replace(os.sep, "/")
    return None if rel.startswith("../") or rel == ".." else "/" + rel


def git_exclude(path: Path) -> str | None:
    """List path in its repository's .git/info/exclude. Returns the exclude file it edited."""
    top = _git(path.parent, "rev-parse", "--show-toplevel")
    if top is None or top.returncode != 0:
        return None
    ignored = _git(path.parent, "check-ignore", "-q", str(path))
    if ignored is not None and ignored.returncode == 0:
        return None
    common = _git(path.parent, "rev-parse", "--git-common-dir")
    if common is None or common.returncode != 0:
        return None
    c = common.stdout.strip()
    common_dir = Path(c) if os.path.isabs(c) else path.parent / c
    pattern = _repo_pattern(path, top.stdout.strip())
    if pattern is None:
        return None
    exclude = common_dir / "info" / "exclude"
    existing = _read(exclude) or ""
    if pattern in existing.splitlines():
        return None
    exclude.parent.mkdir(parents=True, exist_ok=True)
    prefix = "" if not existing or existing.endswith("\n") else "\n"
    with exclude.open("a", encoding="utf-8") as fh:
        fh.write(f"{prefix}{EXCLUDE_COMMENT}\n{pattern}\n")
    return str(exclude)


def git_unexclude(path: Path) -> None:
    """Remove the exclude line git_exclude added for path (uninstall --purge)."""
    res = _git(path.parent, "rev-parse", "--show-toplevel", "--git-common-dir")
    if res is None or res.returncode != 0:
        return
    toplevel, common = res.stdout.strip().split("\n")[:2]
    common_dir = Path(common) if os.path.isabs(common) else path.parent / common
    exclude = common_dir / "info" / "exclude"
    lines = (_read(exclude) or "").split("\n")
    pattern = _repo_pattern(path, toplevel)
    out: list[str] = []
    for i, line in enumerate(lines):
        if line == pattern and i > 0 and lines[i - 1] in (EXCLUDE_COMMENT, LEGACY_EXCLUDE_COMMENT):
            out.pop()
            continue
        out.append(line)
    if out != lines:
        exclude.write_text("\n".join(out), encoding="utf-8")


# ---------------------------------------------------------------- apply


def write_atomic(path: Path, content: str) -> None:
    """Write through a symlink (to its target) and never leave a half-written file."""
    target = path.resolve() if path.is_symlink() else path
    target.parent.mkdir(parents=True, exist_ok=True)
    tmp = target.with_name(f".{target.name}.claude-md-for-codex.tmp")
    tmp.write_text(content, encoding="utf-8")
    try:
        os.chmod(tmp, os.stat(target).st_mode & 0o777)
    except OSError:
        pass
    os.replace(tmp, target)


@dataclass
class Options:
    merger: str = "auto"
    model: str | None = None
    merges_allowed: int = 5
    git_exclude: bool = True
    home: Path = Path.home()


def _create(path: Path, text: str, a: Analysis, state: State, opts: Options) -> None:
    write_atomic(path, text)
    state.created(path, text)
    if a.pair.kind == "project" and opts.git_exclude:
        git_exclude(path)


def _record(a: Analysis, state: State, home: Path) -> None:
    c = _read(a.pair.claude)
    view = r.codex_view(a.pair.claude, c, home, skip=a.pair.agents, allowed_root=a.pair.allowed_root)[0] if c is not None else None
    state.record(a.pair.key, c, view, _read(a.pair.agents))


def apply(a: Analysis, state: State, opts: Options) -> str:
    """Carry out one analysis. Returns a one-line report."""
    p = a.pair
    if a.pair.kind == "project" and a.action not in {"none", "blocked"}:
        busy = git_busy(p.folder)
        if busy:
            return f"skipped: a git {busy} is in progress"

    if a.action == "none":
        if a.claude_text is None:
            return ""
        base = state.baseline(p.key)
        if base is None or base.get("claude") != digest(a.claude_text) or base.get("agents") != digest(a.agents_text):
            _record(a, state, opts.home)
        return ""
    if a.action == "create-agents":
        _create(p.agents, a.view, a, state, opts)
        _record(a, state, opts.home)
        return f"copied {p.claude.name} -> AGENTS.md"
    if a.action == "create-claude":
        claude = p.folder / "CLAUDE.md" if p.kind == "project" else p.claude
        _create(claude, a.agents_text, a, state, opts)
        p.claude = claude
        _record(a, state, opts.home)
        return "copied AGENTS.md -> CLAUDE.md"
    if a.action == "update-agents":
        state.backup(p.agents)
        write_atomic(p.agents, a.view)
        _record(a, state, opts.home)
        return f"updated AGENTS.md from {p.claude.name}"
    if a.action == "update-claude":
        state.backup(p.claude)
        write_atomic(p.claude, a.agents_text)
        _record(a, state, opts.home)
        return f"updated {p.claude.name} from AGENTS.md"
    if a.action == "remove-agents":
        state.backup(p.agents)
        p.agents.unlink()
        return "removed AGENTS.md (generated by 0.1 from a CLAUDE.md that is gone)"
    if a.action == "merge":
        return _merge(a, state, opts)
    return f"skipped: {a.detail}"


def import_token(p: Pair, home: Path) -> str:
    """The import line that makes CLAUDE.md read AGENTS.md (`@AGENTS.md`, `@~/.codex/AGENTS.md`)."""
    if p.claude.parent == p.agents.parent:
        return "@AGENTS.md"
    if p.claude.parent.name == ".claude" and p.claude.parent.parent == p.agents.parent:
        return "@../AGENTS.md"
    try:
        return "@~/" + p.agents.relative_to(home).as_posix()
    except ValueError:
        return "@" + str(p.agents)


def _merge(a: Analysis, state: State, opts: Options) -> str:
    p = a.pair
    claude_input = a.view if a.style == "stub" else a.claude_text
    pair_id = digest(f"{a.style}\0{claude_input}\0{a.agents_text}")[:16]
    record = state.cached_merge(pair_id)
    source = "reused an earlier merge of the same texts"
    if record is None:
        if opts.merges_allowed <= 0:
            return "merge postponed: this run's merge limit is used up"
        err = state.failed_recently(pair_id)
        if err:
            return f"merge skipped: it failed within the last day ({err})"
        opts.merges_allowed -= 1
        where = "your global instructions" if p.kind == "global" else f"in the folder {p.folder}"
        history = f"- what changed since the last sync: {CASES[a.case]}"
        prompt = m.build_prompt(where, p.claude, claude_input, p.agents, a.agents_text, history=history,
                                stub_token=a.stub_token, has_imports=a.style == "imports",
                                import_token=import_token(p, opts.home))
        try:
            raw = m.run_merger(prompt, opts.merger, opts.model)
            result = m.parse_answer(raw, claude_input, a.agents_text)
        except m.MergeError as exc:
            state.failed(pair_id, str(exc))
            state.save_merge(pair_id, {"ok": False, "folder": str(p.folder), "error": str(exc)})
            return f"merge failed: {exc}"
        record = {"ok": True, "folder": str(p.folder), "case": a.case, "style": a.style,
                  "decision": result.decision, "reason": result.reason, "content": result.content,
                  "claude_md": result.claude_md, "answer": result.raw, "merger": opts.merger}
        state.save_merge(pair_id, record)
        source = f"merged with {opts.merger}"

    state.backup(p.claude)
    state.backup(p.agents)
    merged = record["content"]
    if a.style == "stub" or record.get("claude_md") == "import":
        write_atomic(p.agents, merged)
        write_atomic(p.claude, (a.stub_token or import_token(p, opts.home)) + "\n")
    else:
        write_atomic(p.claude, merged)
        view = r.codex_view(p.claude, merged, opts.home, skip=p.agents, allowed_root=p.allowed_root)[0]
        write_atomic(p.agents, view)
    _record(a, state, opts.home)
    return f"{source}: {record['decision']} - {record['reason']}"
